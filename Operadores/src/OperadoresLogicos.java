/* AND &&
 * OR ||
 * NOT !
 */

public class OperadoresLogicos {
    public static void main(String[] args) {
        boolean x = true, y = false;

        System.out.println("x AND y: " + (x && y));
        System.out.println("x OR y: " + (x || y));
        System.out.println("x NOT : " + (!x));

    }
}
